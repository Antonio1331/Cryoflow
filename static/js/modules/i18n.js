export function getCurrentLang() {
    return localStorage.getItem('cryoflow_lang') || 'ru';
}

export function setCurrentLang(lang) {
    const safeLang = TRANSLATIONS[lang] ? lang : 'ru';
    localStorage.setItem('cryoflow_lang', safeLang);
    document.documentElement.lang = safeLang;
    applyStaticTranslations(safeLang);
    return safeLang;
}

export function t(key, lang = getCurrentLang()) {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.ru;
    return dict[key] || TRANSLATIONS.ru[key] || key;
}

export function applyStaticTranslations(lang = getCurrentLang()) {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.ru;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });
}